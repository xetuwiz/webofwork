#: The migration ID is pinned, not stamped at run time.
#:
#: This migration is already recorded in ``__EFMigrationsHistory`` on every
#: database that has the table, so regenerating it with a fresh timestamp would
#: produce a *new* ID that EF then tries to apply against a table that already
#: exists -- ``CREATE TABLE market_price_references`` and a hard failure.
#:
#: Pinning it means the generator is safely re-runnable: regenerate, and the
#: result still matches what the database already has.
MIGRATION_STAMP = "20261004121033"

SOURCE = "Upwork public category/package pages (advertised reference bands)"


def sql_literal(value) -> str:
    """A quoted SQL literal. Doubling the quote is the only escape these need."""
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def dedupe(bands):
    """Drop rows sharing (category, deliverable, level).

    A duplicate would violate `ix_market_price_references_identity` rather than
    being ignored, which aborts the migration halfway. Deduping here means the
    script reports the collision instead.
    """
    seen = set()
    unique = []
    for row in bands:
        key = (row[0], row[1].lower(), row[2].lower())
        if key in seen:
            continue
        seen.add(key)
        unique.append(row)
    return unique


def main():
    bands = dedupe(BANDS)
    dropped = len(BANDS) - len(bands)
    if dropped:
        print(f"  note: dropped {dropped} duplicate (category, deliverable, level) rows")

    out = [HEADER]

    def a(text):
        out.append(text)

    a("            // Category resolved by NAME, because ids differ between a\n"
      "      // populated and an empty database. A category that does not exist\n"
      "      // leaves category_id NULL, which the table treats as \"any category\" --\n"
      "      // so a renamed or absent category degrades to a generic row instead\n"
      "      // of aborting the whole migration.\n"
      "      //\n"
      "      // The NOT EXISTS guard keys on the same triple the unique index\n"
      "      // constrains, so re-running refreshes numbers instead of failing.\n\n")

    for category, deliverable, level, lo, hi, dmin, dmax in bands:
        cat_sql = (
            f"(SELECT id FROM categories WHERE name = {sql_literal(category)})"
            if category
            else "NULL"
        )
        a("            migrationBuilder.Sql(\n")
        a("                $\"INSERT INTO market_price_references "
          "(category_id, deliverable, level, min_price_usd, max_price_usd, "
          "typical_days_min, typical_days_max, source, created_at) "
          f"SELECT {cat_sql}, {sql_literal(deliverable)}, {sql_literal(level)}, "
          f"{sql_literal(lo)}, {sql_literal(hi)}, {sql_literal(dmin)}, "
          f"{sql_literal(dmax)}, {sql_literal(SOURCE)}, now() "
          "WHERE NOT EXISTS (SELECT 1 FROM market_price_references r "
          "WHERE COALESCE(r.deliverable, '') = "
          f"{sql_literal(deliverable)} "
          "AND COALESCE(r.level, '') = "
          f"{sql_literal(level)} "
          f"AND COALESCE(r.category_id, 0) = COALESCE({cat_sql}, 0));\");\n")

    out.append(FOOTER.replace("{source_sql}", SOURCE.replace("'", "''")))

    stamp = MIGRATION_STAMP
    target = f"server/WebOfWork.Api/Data/Migrations/{stamp}_SeedMarketPriceReferenceData.cs"
    migration_id = f"{stamp}_SeedMarketPriceReferenceData"
    body = "".join(out).replace("{migration_id}", migration_id)
    with open(target, "w", encoding="utf-8", newline="\r\n") as handle:
        handle.write(body)

    print(f"wrote {target}")
    print(f"  migration id: {migration_id}")
    print(f"  {len(bands)} price bands across "
          f"{len({b[0] for b in bands if b[0]})} categories")


if __name__ == "__main__":
    main()