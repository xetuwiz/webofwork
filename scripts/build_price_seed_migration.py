"""Generate the SeedMarketPriceReferenceData migration from the bands below.

Kept as a script (not hand-written SQL) for the same reason as
``build_seed_migration.py``: the data stays reviewable as data, and the SQL is a
generated artefact rather than the thing a human edits.

    python scripts/build_price_seed_migration.py

## What these numbers are, and are not

They are *advertised reference bands* collected from a marketplace's public
category and package pages. That is the same category of number such a page
shows a seller as guidance, not a record of what was transacted.

Observed freelancer profiles on the same marketplace span roughly $3/hr to
$85/hr -- far outside the stated bands. So every row here is a defensible
starting point, never a quote, and the ``source`` column carries the provenance
so the drafter can attribute it rather than assert it. Nothing in the system may
call these "the market rate"; see :class:`MarketPriceReference`.

## Why the deliverable column is free text

A client asking "what does a landing page cost?" does not know or care that the
platform files it under "Front-End Developers". Keying on the skill taxonomy
would make the table unfindable by the only party meant to read it. The agent
matches on wording, so these are written as a client would say them.

## Why the level vocabulary is loose

"entry", "intermediate", "expert" are the source's own bands, but it also uses
compounds carrying real information -- "entry-mid", "intermediate-expert" --
and collapsing those into three buckets discards exactly the distinction that
makes a band useful. A hard enum cannot represent them.

## Why this is a separate migration from the table

The schema migration is generated by ``dotnet ef migrations add`` and owns the
model snapshot. This one owns only the data. Splitting them means the table can
be recreated by EF without this file's INSERTs being lost, and a bad band can be
corrected by regenerating and re-running this alone.
"""

