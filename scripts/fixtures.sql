-- Deterministic fixture data for end-to-end workflow testing.
-- Idempotent: every insert is guarded with NOT EXISTS, so re-running tops up
-- rather than duplicating. Plain SQL on purpose -- the previous Python
-- generator was fragile with nested f-string quoting, and none of this needs
-- to be computed.
--
-- Enum values (from server/Models/Enums):
--   UserRole       1=Client 2=Freelancer 3=Admin      UserStatus 2=Active
--   ProjectStatus  1=Open 2=InProgress 3=Completed    Pricing 1=Fixed 2=Range
--   ContractStatus 0=Offered 1=Active 2=Submitted 3=Completed 5=Disputed
--   PaymentStatus  1=Pending 2=Escrow 3=Released 4=Refunded
--   ProposalStatus 0=Pending 1=Accepted 2=Rejected
--   InvitationStatus 0=Pending 1=Accepted 2=Declined
--   DisputeStatus  1=Pending 3=Resolved 4=Rejected
--
-- The password hash below is a BCrypt (work factor 11) hash of "Password1#"
-- generated by the app's own hasher -- seed_fixtures.py writes the current one
-- in via psql variable :'hash' so it always matches PasswordHasher.cs.

\set ON_ERROR_STOP on
-- ── realign identity sequences ───────────────────────────────────────────
-- Every int id here is GENERATED BY DEFAULT AS IDENTITY. The fixtures below
-- omit the id column so the database assigns it, which only works while each
-- sequence is at or ahead of MAX(id). A restored pg_dump, or an older seeder
-- that inserted explicit ids, can leave a sequence behind -- the next insert
-- then fails with a duplicate-key error on the primary key.
DO $$
DECLARE t text;
BEGIN
  FOR t IN
    SELECT table_name FROM information_schema.columns
     WHERE column_name = 'id' AND table_schema = 'public'
       AND is_identity = 'YES'
  LOOP
    EXECUTE format(
      'select setval(%L, greatest((select coalesce(max(id),0) from %I),0)+1, false)',
      t || '_id_seq', t);
  END LOOP;
END $$;



